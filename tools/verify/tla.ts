import { Array as EffectArray } from "effect"

export type TlaValue = string | boolean | number

const literal = (value: TlaValue): string => {
  if (typeof value === "string") return `"${value}"`

  if (typeof value === "boolean") return value ? "TRUE" : "FALSE"

  return `${value}`
}

const tuple = (row: ReadonlyArray<TlaValue>) => `<<${EffectArray.join(EffectArray.map(row, literal), ", ")}>>`

export const tlaRows = (name: string, rows: ReadonlyArray<ReadonlyArray<TlaValue>>): string =>
  `${name} == {\n${EffectArray.join(
    EffectArray.map(rows, (row) => `  ${tuple(row)}`),
    ",\n"
  )}\n}`

export const tlaConstant = (name: string, value: TlaValue): string => `${name} == ${literal(value)}`

export const tlaModule = (name: string, sources: ReadonlyArray<string>, definitions: ReadonlyArray<string>): string =>
  EffectArray.join(
    [
      `---- MODULE ${name} ----`,
      `\\* Generated by tools/verify from the real code in ${EffectArray.join(sources, ", ")}.`,
      "\\* Do not edit: rerun the verify command instead.",
      "",
      ...EffectArray.map(definitions, (definition) => `${definition}\n`),
      "===="
    ],
    "\n"
  )
